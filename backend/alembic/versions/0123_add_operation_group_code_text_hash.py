"""Store the hash of the code-written group text on each group row (#4332).

Revision ID: 0123
Revises: 0122
Create Date: 2026-10-29

A group text (``operation_group.when_to_use``) of a typed connector is
written when the group row is created. Before this change, a later text
change in the code never reached an existing row. Now the start-up
registration keeps the SHA-256 of the code text it last wrote in the new
nullable column ``code_text_hash``. A row whose text still matches that
hash gets the new code text at start-up. A row an operator edited
(``meho connector edit-group``) no longer matches, so it is kept.

What this migration does
------------------------

* Adds ``operation_group.code_text_hash`` (``Text``, nullable).
* Fills it for built-in rows (``tenant_id IS NULL``) whose text is a
  text MEHO shipped before. Such a row then refreshes like any other.
  Rows with any other text (operator edits, texts from spec ingestion)
  stay NULL and are never overwritten. A row whose text equals the code
  text of the running version gets its hash at start-up anyway.

Where the shipped texts come from
---------------------------------

:data:`_SHIPPED_TEXT_HASHES` holds the SHA-256 (hex, UTF-8) of every
group text that a fresh install wrote, for every release tag from
``v0.2.0`` to ``v0.38.0`` and for ``main`` when this migration was
written. They were collected by running each version's own typed-op
registrars against an empty test database and reading back the
``operation_group`` rows. This set includes every text migration
``0011`` wrote, and the old placeholder texts (``Operations grouped
under ...``) of the first versions. Only hashes are stored: the texts
themselves are long, and the migration needs only to recognise them.

The list is written out here, not computed from connector code, so the
migration keeps working when that code changes.

``downgrade()`` drops the column. The texts themselves are not changed.
"""

